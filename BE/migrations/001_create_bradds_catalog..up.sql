-- ============================================================
-- 1. MASTER DATA
-- ============================================================

-- 1.1 Categories
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    slug VARCHAR(180) NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    image_url TEXT NOT NULL DEFAULT '',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_categories_name
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_categories_slug
        CHECK (LENGTH(TRIM(slug)) > 0)
);


-- 1.2 Colors
CREATE TABLE colors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    hex_code VARCHAR(7) NOT NULL DEFAULT '#000000',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_colors_hex_code
        CHECK (hex_code ~ '^#[0-9A-Fa-f]{6}$')
);


-- 1.3 Sizes
CREATE TABLE sizes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) NOT NULL UNIQUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_sizes_sort_order
        CHECK (sort_order >= 0)
);


-- 1.4 Collections
CREATE TABLE collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    slug VARCHAR(180) NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    image_url TEXT NOT NULL DEFAULT '',
    cover_media_id BIGINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_collections_name
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_collections_sort_order
        CHECK (sort_order >= 0)
);


-- ============================================================
-- 2. MEDIA ASSETS
-- Central metadata for images and videos
-- ============================================================

CREATE TABLE media_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    file_url TEXT NOT NULL,
    storage_provider VARCHAR(30) NOT NULL DEFAULT 'local',
    bucket VARCHAR(150),
    storage_key TEXT,

    media_type VARCHAR(20) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    original_filename VARCHAR(255) NOT NULL DEFAULT '',
    file_size_bytes BIGINT NOT NULL DEFAULT 0,

    width INTEGER,
    height INTEGER,
    duration_seconds NUMERIC(10,2),
    poster_url TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'ready',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_media_type
        CHECK (media_type IN ('image', 'video')),

    CONSTRAINT chk_media_status
        CHECK (status IN ('uploading', 'ready', 'failed')),

    CONSTRAINT chk_media_file_size
        CHECK (file_size_bytes >= 0),

    CONSTRAINT chk_media_width
        CHECK (width IS NULL OR width > 0),

    CONSTRAINT chk_media_height
        CHECK (height IS NULL OR height > 0),

    CONSTRAINT chk_media_duration
        CHECK (duration_seconds IS NULL OR duration_seconds >= 0),

    CONSTRAINT chk_media_storage_provider
        CHECK (storage_provider IN ('local', 's3', 'r2'))
);


-- Add media reference to collections
ALTER TABLE collections
    ADD CONSTRAINT fk_collections_cover_media
    FOREIGN KEY (cover_media_id)
    REFERENCES media_assets(id)
    ON DELETE SET NULL;


-- ============================================================
-- 3. PRODUCTS
-- ============================================================

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category_id BIGINT NOT NULL
        REFERENCES categories(id)
        ON DELETE RESTRICT,

    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,

    description TEXT NOT NULL DEFAULT '',
    price NUMERIC(14,2) NOT NULL DEFAULT 0,

    material VARCHAR(150) NOT NULL DEFAULT '',
    care_instruction TEXT NOT NULL DEFAULT '',

    status VARCHAR(20) NOT NULL DEFAULT 'not_ready',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_products_price
        CHECK (price >= 0),

    CONSTRAINT chk_products_status
        CHECK (
            status IN (
                'ready',
                'not_ready',
                'discontinued'
            )
        ),

    CONSTRAINT chk_products_name
        CHECK (LENGTH(TRIM(name)) > 0)
);


-- ============================================================
-- 4. PRODUCT MEDIA
-- Replaces product_images as the media relationship table
-- Supports both images and videos
-- ============================================================

CREATE TABLE product_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL
        REFERENCES products(id)
        ON DELETE CASCADE,

    media_id BIGINT NOT NULL
        REFERENCES media_assets(id)
        ON DELETE RESTRICT,

    media_role VARCHAR(20) NOT NULL DEFAULT 'gallery',

    sort_order INTEGER NOT NULL DEFAULT 0,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,

    -- Backward compatibility with existing FE
    alt_text VARCHAR(255) NOT NULL DEFAULT '',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_product_media
        UNIQUE (product_id, media_id),

    CONSTRAINT chk_product_media_role
        CHECK (
            media_role IN ('cover', 'gallery', 'video')
        ),

    CONSTRAINT chk_product_media_sort_order
        CHECK (sort_order >= 0)
);


-- Only one primary media per product
CREATE UNIQUE INDEX uq_product_primary_media
    ON product_media (product_id)
    WHERE is_primary = TRUE;


-- ============================================================
-- 5. PRODUCT VARIANTS
-- ============================================================

CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL
        REFERENCES products(id)
        ON DELETE CASCADE,

    color_id BIGINT NOT NULL
        REFERENCES colors(id)
        ON DELETE RESTRICT,

    size_id BIGINT NOT NULL
        REFERENCES sizes(id)
        ON DELETE RESTRICT,

    sku VARCHAR(100) NOT NULL UNIQUE,

    stock INTEGER NOT NULL DEFAULT 0,
    price NUMERIC(14,2) NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_product_variant
        UNIQUE (product_id, color_id, size_id),

    CONSTRAINT chk_variant_stock
        CHECK (stock >= 0),

    CONSTRAINT chk_variant_price
        CHECK (price >= 0)
);


-- ============================================================
-- 6. PRODUCT COLLECTIONS
-- Many-to-many relationship
-- ============================================================

CREATE TABLE product_collections (
    product_id BIGINT NOT NULL
        REFERENCES products(id)
        ON DELETE CASCADE,

    collection_id BIGINT NOT NULL
        REFERENCES collections(id)
        ON DELETE CASCADE,

    PRIMARY KEY (product_id, collection_id)
);


-- ============================================================
-- 7. BANNERS
-- ============================================================

CREATE TABLE banners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL DEFAULT '',

    -- Existing FE image URL
    image_url TEXT NOT NULL DEFAULT '',

    -- Central media reference (image or video)
    media_id BIGINT
        REFERENCES media_assets(id)
        ON DELETE SET NULL,

    link_url TEXT NOT NULL DEFAULT '',

    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    start_at TIMESTAMPTZ,
    end_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_banners_sort_order
        CHECK (sort_order >= 0),

    CONSTRAINT chk_banners_schedule
        CHECK (
            end_at IS NULL
            OR start_at IS NULL
            OR end_at > start_at
        )
);


-- ============================================================
-- 8. ADMIN USERS
-- ============================================================

CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,

    role VARCHAR(30) NOT NULL DEFAULT 'admin',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_admin_role
        CHECK (role IN ('admin', 'super_admin')),

    CONSTRAINT chk_admin_email
        CHECK (LENGTH(TRIM(email)) > 0)
);


